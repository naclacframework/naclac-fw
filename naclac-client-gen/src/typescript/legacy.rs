use super::shared::map_type_to_ts;
use crate::{Idl, IdlInstruction, IdlPda, IdlSeed};
use heck::{ToLowerCamelCase, ToUpperCamelCase};
use std::fs;

pub fn generate_legacy_client(
    idl: &Idl,
    program_name: &str,
    clients_dir: &std::path::Path,
) -> Result<(), Box<dyn std::error::Error>> {
    let header = "// 🛑 DO NOT EDIT - AUTO-GENERATED BY NACLAC\n// Re-run `naclac generate` to refresh this file.\n\n";
    let type_name = program_name.to_upper_camel_case();

    let mut client_content = header.to_string();

    client_content.push_str("import * as naclac from \"@naclac-fw/client/legacy\";\n");
    client_content.push_str(&format!(
        "import rawIDL from \"./idl/{program_name}.json\";\n\
         import type {{ {type_name} }} from \"./idl/{program_name}\";\n\
         const IDL = rawIDL as unknown as {type_name};\n"
    ));

    if !idl.instructions.is_empty() {
        client_content.push_str("import * as instructions from \"./instructions\";\n");
    }
    if !idl.accounts.is_empty() {
        client_content.push_str("import * as accounts from \"./accounts/legacy\";\n");
    }
    client_content.push_str("import * as types from \"./types\";\n");

    // ── Class declaration ─────────────────────────────────────────────────────
    client_content.push_str(&format!("\n/**\n * High-level client for the `{program_name}` program.\n * Uses the classic @solana/web3.js (v1) transaction model.\n */\nexport class {type_name}Client {{\n"));
    client_content.push_str("  public readonly program: naclac.LegacyProgram;\n");
    if !idl.instructions.is_empty() {
        client_content.push_str("  public readonly instructions = instructions;\n");
    }
    if !idl.accounts.is_empty() {
        client_content.push_str("  public readonly accounts = accounts;\n");
    }
    client_content.push_str("  public readonly types = types;\n");
    client_content.push_str("  public readonly errors = types.ProgramErrors;\n");

    client_content
        .push_str("\n  public get constants() {\n    return this.program.constants;\n  }\n");
    client_content.push_str("\n  /** The on-chain program address as a `PublicKey`. */\n  public get programId(): naclac.PublicKey {\n    return this.program.programId;\n  }\n");

    // ── Constructor ───────────────────────────────────────────────────────────
    client_content.push_str("\n  constructor(\n    providerOrCluster: naclac.LegacyProvider | \"devnet\" | \"mainnet\" | \"localnet\" | string,\n    payer?: naclac.Keypair\n  ) {\n");
    client_content.push_str("    let provider: naclac.LegacyProvider;\n");
    client_content.push_str("    if (typeof providerOrCluster === \"string\") {\n");
    client_content.push_str("      let url = providerOrCluster;\n");
    client_content.push_str(
        "      if (providerOrCluster === \"devnet\") url = \"https://api.devnet.solana.com\";\n",
    );
    client_content.push_str("      else if (providerOrCluster === \"mainnet\") url = \"https://api.mainnet-beta.solana.com\";\n");
    client_content.push_str(
        "      else if (providerOrCluster === \"localnet\") url = \"http://127.0.0.1:8899\";\n",
    );
    client_content
        .push_str("      const connection = new naclac.Connection(url, \"confirmed\");\n");
    client_content.push_str(
        "      provider = { connection, payer, publicKey: payer ? payer.publicKey : undefined };\n",
    );
    client_content.push_str("    } else {\n      provider = providerOrCluster;\n    }\n");
    client_content.push_str("    this.program = new naclac.LegacyProgram(IDL, provider);\n");
    client_content.push_str("  }\n\n");

    // ── Instruction methods ───────────────────────────────────────────────────
    for ix in &idl.instructions {
        // `instructions.{ix_camel}` must match the export name shared.rs's
        // per-instruction generator actually writes — the class method name
        // itself is a separate, purely cosmetic choice.
        let ix_camel = ix.name.to_lower_camel_case();
        let ix_name_pascal = ix.name.to_upper_camel_case();
        let has_args = ix.args.iter().any(|a| a.name != "ctx");

        let args_param = if has_args {
            format!("args: instructions.{ix_name_pascal}Args")
        } else {
            "args?: Record<string, never>".to_string()
        };

        client_content.push_str(&format!(
            "  /**\n   * Builds the `{ix_camel}` instruction pipeline.\n   * Call `.rpc()` to send or `.transaction()` to get a `Transaction` object.\n   */\n  public {ix_camel}({args_param}, accounts?: Partial<instructions.{ix_name_pascal}Accounts>) {{\n"
        ));
        client_content.push_str(&format!(
            "    return instructions.{ix_camel}(this.program, args ?? {{}}, accounts);\n"
        ));
        client_content.push_str("  }\n\n");
    }

    // ── PDA helpers ───────────────────────────────────────────────────────────
    // Uses naclac.PublicKey.findProgramAddressSync — no direct @solana/web3.js needed.
    let mut account_pdas: std::collections::HashMap<String, Vec<(&IdlInstruction, &IdlPda)>> =
        std::collections::HashMap::new();
    for ix in &idl.instructions {
        for acc in &ix.accounts {
            if let Some(pda) = &acc.pda {
                account_pdas
                    .entry(acc.name.clone())
                    .or_default()
                    .push((ix, pda));
            }
        }
    }

    let mut sorted_acc_names: Vec<String> = account_pdas.keys().cloned().collect();
    sorted_acc_names.sort();

    for acc_name in sorted_acc_names {
        let pdas = &account_pdas[&acc_name];

        let (ix, pda) = pdas
            .iter()
            .max_by_key(|(ix, pda)| {
                let mut score: i64 = 0;
                if ix.name.starts_with("create") || ix.name.starts_with("init") {
                    score += 50;
                }
                let pda_count = ix.accounts.iter().filter(|a| a.pda.is_some()).count() as i64;
                score -= pda_count * 10;
                for seed in &pda.seeds {
                    match seed {
                        IdlSeed::Arg { path } => {
                            if ix.args.iter().any(|a| a.name == *path) {
                                score += 10;
                            } else {
                                score -= 5;
                            }
                        }
                        IdlSeed::Account { path, .. } => {
                            if *path == acc_name {
                                score -= 30;
                            } else if ix
                                .accounts
                                .iter()
                                .any(|a| a.name == *path && a.pda.is_none())
                            {
                                score += 5;
                            } else if ix.accounts.iter().any(|a| a.name == *path) {
                                score += 2;
                            }
                        }
                        _ => {}
                    }
                }
                score
            })
            .unwrap();

        // See the matching comment in kit.rs's generator: a dotted seed path
        // like `registry.bump` is a field read from another account, not
        // that account's own address. When naclac-syn resolved the field's
        // real type (`field_type: Some(_)`), the loops below generate
        // correct code for it via naclac.getIdlCodec. Only skip when the
        // type genuinely couldn't be resolved (a nested/defined type).
        if let Some(IdlSeed::Account { path, .. }) = pda.seeds.iter().find(
            |s| matches!(s, IdlSeed::Account { path, field_type: None } if path.contains('.')),
        ) {
            client_content.push_str(&format!(
                "// get{}Pda intentionally not generated: this PDA's seeds include\n\
                 // `{}`, a field read from another account whose type is not a plain\n\
                 // primitive — naclac-syn couldn't resolve it from the backing\n\
                 // component's struct definition. Derive it manually — fetch the\n\
                 // account, read the field, and call\n\
                 // naclac.PublicKey.findProgramAddressSync yourself with the correct\n\
                 // byte encoding for that field's type.\n\n",
                acc_name.to_upper_camel_case(),
                path
            ));
            continue;
        }

        let type_name_pda = acc_name.to_upper_camel_case();
        client_content.push_str(&format!("  /** Derives the PDA for a `{acc_name}` account. Returns `[PublicKey, bumpSeed]`. */\n  public get{type_name_pda}Pda(seeds: {{\n"));

        let mut seen_seeds = std::collections::HashSet::new();
        for seed in &pda.seeds {
            match seed {
                IdlSeed::Arg { path } => {
                    let (root, is_nested) = if path.contains('.') {
                        (path.split('.').next().unwrap(), true)
                    } else {
                        (path.as_str(), false)
                    };
                    if seen_seeds.contains(root) {
                        continue;
                    }
                    seen_seeds.insert(root.to_string());
                    let mut arg_ty = if is_nested {
                        ix.args
                            .iter()
                            .find(|a| a.name == root)
                            .map(|a| map_type_to_ts(&a.ty, idl.is_zero_copy))
                            .unwrap_or_else(|| "any".to_string())
                    } else {
                        ix.args
                            .iter()
                            .find(|a| a.name == *path)
                            .map(|a| map_type_to_ts(&a.ty, idl.is_zero_copy))
                            .unwrap_or_else(|| "any".to_string())
                    };
                    if idl.defined_types.iter().any(|t| t.name == arg_ty) {
                        arg_ty = format!("types.{}", arg_ty);
                    }
                    client_content.push_str(&format!("    {root}: {arg_ty};\n"));
                }
                IdlSeed::Account { path, field_type } => {
                    if seen_seeds.contains(path) {
                        continue;
                    }
                    if *path == acc_name {
                        continue;
                    }
                    seen_seeds.insert(path.clone());
                    if let Some(field_ty) = field_type {
                        // Resolved field-access seed (e.g. `registry.bump: u8`).
                        // `.` isn't valid in a plain TS property key.
                        let key = path.replace('.', "_");
                        let ts_ty = map_type_to_ts(&serde_json::json!(field_ty), idl.is_zero_copy);
                        client_content.push_str(&format!("    {key}: {ts_ty};\n"));
                    } else {
                        // PublicKey | string — no direct web3.js import, naclac re-exports PublicKey
                        client_content
                            .push_str(&format!("    {path}: naclac.PublicKey | string;\n"));
                    }
                }
                _ => {}
            }
        }
        // Returns [PublicKey, number] — synchronous in web3.js v1
        client_content.push_str("  }): [naclac.PublicKey, number] {\n");

        let mut seeds_exprs = Vec::new();
        for seed in &pda.seeds {
            match seed {
                IdlSeed::Const { value, .. } => {
                    let bytes_str = value
                        .iter()
                        .map(|b| b.to_string())
                        .collect::<Vec<String>>()
                        .join(", ");
                    seeds_exprs.push(format!("new Uint8Array([{bytes_str}])"));
                }
                IdlSeed::Arg { path } => {
                    let arg_ty = crate::resolve_leaf_type(path, &ix.args, &idl.defined_types);
                    let arg_ty_json = match arg_ty {
                        Some(ty) => serde_json::to_string(&ty).unwrap(),
                        None => "\"any\"".to_string(),
                    };
                    // naclac.getIdlCodec is re-exported from @naclac-fw/client/legacy
                    seeds_exprs.push(format!(
                        "new Uint8Array(naclac.getIdlCodec(JSON.parse('{arg_ty_json}')).encode(seeds.{path}))"
                    ));
                }
                IdlSeed::Account { path, field_type } => {
                    if let Some(field_ty) = field_type {
                        // Resolved field-access seed — same generic codec
                        // path the `IdlSeed::Arg` branch above uses.
                        let key = path.replace('.', "_");
                        let ty_json = serde_json::to_string(field_ty).unwrap();
                        seeds_exprs.push(format!(
                            "new Uint8Array(naclac.getIdlCodec(JSON.parse('{ty_json}')).encode(seeds.{key}))"
                        ));
                    } else {
                        // toBuffer() is a web3.js v1 PublicKey method — safe via naclac.PublicKey
                        seeds_exprs.push(format!("new naclac.PublicKey(seeds.{path}).toBuffer()"));
                    }
                }
            }
        }
        // `seeds::program = X` means this PDA belongs to a different program
        // than the one this client targets — derive against that program's ID
        // instead of `this.programId`, or the computed address is simply wrong.
        let owner_program_expr = match &pda.program {
            Some(IdlSeed::Const { value, .. }) => {
                let bytes_str = value
                    .iter()
                    .map(|b| b.to_string())
                    .collect::<Vec<String>>()
                    .join(", ");
                format!("new naclac.PublicKey(new Uint8Array([{bytes_str}]))")
            }
            _ => "this.programId".to_string(),
        };
        client_content.push_str(&format!(
            "    const [pda, bump] = naclac.PublicKey.findProgramAddressSync(\n      [\n        {}\n      ],\n      {owner_program_expr}\n    );\n    return [pda, bump];\n",
            seeds_exprs.iter().map(|s| format!("        {s}")).collect::<Vec<String>>().join(",\n")
        ));
        client_content.push_str("  }\n\n");
    }

    // ── Account fetch helpers ─────────────────────────────────────────────────
    for acct in &idl.accounts {
        let acct_name = &acct.name;

        client_content.push_str(&format!(
            "  /** Fetches a `{acct_name}` account. Throws if it does not exist. */\n  public fetch{acct_name}(address: naclac.PublicKey | string) {{\n    return this.program.account['{acct_name}'].fetch(address);\n  }}\n\n"
        ));

        client_content.push_str(&format!(
            "  /** Fetches a `{acct_name}` account. Returns `null` if it does not exist. */\n  public async fetchMaybe{acct_name}(address: naclac.PublicKey | string) {{\n    try {{ return await this.program.account['{acct_name}'].fetch(address); }}\n    catch {{ return null; }}\n  }}\n\n"
        ));

        client_content.push_str(&format!(
            "  /** Fetches multiple `{acct_name}` accounts in a single RPC call. */\n  public fetchAll{acct_name}s(addresses: Array<naclac.PublicKey | string>, opts?: {{ dropCorrupted?: boolean }}) {{\n    return this.program.account['{acct_name}'].fetchMultiple(addresses, opts);\n  }}\n\n"
        ));

        client_content.push_str(&format!(
            "  /** Fetches all on-chain `{acct_name}` accounts owned by this program. */\n  public fetchAll{acct_name}ByOwner(options?: {{ dropCorrupted?: boolean; filters?: any[] }}) {{\n    return this.program.account['{acct_name}'].all(options);\n  }}\n\n"
        ));
    }

    // ── Event helpers ─────────────────────────────────────────────────────────
    for event in &idl.events {
        client_content.push_str(&format!("  /** Subscribes to `{}` events. Returns a listener ID. */\n  public on{}(callback: (event: types.{}, slot: number, signature: string) => void) {{\n", event.name, event.name, event.name));
        client_content.push_str(&format!(
            "    return types.add{}Listener(this.program, callback);\n",
            event.name
        ));
        client_content.push_str("  }\n\n");

        client_content.push_str(&format!("  /** Awaits the next `{}` event. Resolves `null` on timeout. */\n  public waitFor{}(options?: {{ timeoutMs?: number }}) {{\n", event.name, event.name));
        client_content.push_str(&format!(
            "    return this.program.waitForEvent<types.{}>(\"{}\", options);\n",
            event.name, event.name
        ));
        client_content.push_str("  }\n\n");

        client_content.push_str(&format!(
            "  /** Decodes every `{}` event found in an already-fetched list of transaction log lines (e.g. `.rpc()`'s returned `logs`). Race-free, unlike `waitFor{}` — prefer this when you already know which transaction you're checking. */\n  public parse{}Events(logs: readonly string[]) {{\n",
            event.name, event.name, event.name
        ));
        client_content.push_str(&format!(
            "    return this.program.parseEvents<types.{}>(\"{}\", logs);\n",
            event.name, event.name
        ));
        client_content.push_str("  }\n\n");
    }
    if !idl.events.is_empty() {
        client_content.push_str("  /** Removes a registered event listener by its ID. */\n  public removeEventListener(listenerId: number) {\n");
        client_content
            .push_str("    return types.removeListener(this.program, listenerId);\n  }\n");
    }

    client_content.push_str("}\n");

    fs::write(clients_dir.join("client-legacy.ts"), client_content)?;

    // ── Legacy account fetchers (delegates to program.account.X LegacyAccountFetcher) ──
    let mut accounts_index = header.to_string();
    for acct in &idl.accounts {
        let acct_name = &acct.name;
        let file_name = acct_name.to_lowercase();
        accounts_index.push_str(&format!("export * from \"./{file_name}\";\n"));

        let mut f = header.to_string();
        f.push_str("import * as naclac from \"@naclac-fw/client/legacy\";\n");
        f.push_str(&format!(
            "import type {{ {acct_name} }} from \"../../types\";\n\n"
        ));

        // Discriminator
        if let Some(disc) = &acct.discriminator {
            let arr = disc
                .iter()
                .map(|b| b.to_string())
                .collect::<Vec<_>>()
                .join(", ");
            f.push_str(&format!(
                "/** 8-byte on-chain discriminator for `{acct_name}` accounts. */\nexport const {}_DISCRIMINATOR = new Uint8Array([{arr}]);\n\n",
                acct_name.to_uppercase()
            ));
        }

        // fetch — throws if missing
        f.push_str(&format!(
            "/** Fetches a `{acct_name}` account. Throws if it does not exist. */\nexport async function fetch{acct_name}(\n  program: naclac.LegacyProgram,\n  address: naclac.PublicKey | string,\n): Promise<{acct_name}> {{\n  const result = await program.account['{acct_name}'].fetch(address);\n  return result as unknown as {acct_name};\n}}\n\n"
        ));

        // fetchMaybe — returns null if missing
        f.push_str(&format!(
            "/** Fetches a `{acct_name}` account. Returns `null` if it does not exist. */\nexport async function fetchMaybe{acct_name}(\n  program: naclac.LegacyProgram,\n  address: naclac.PublicKey | string,\n): Promise<{acct_name} | null> {{\n  try {{\n    const result = await program.account['{acct_name}'].fetch(address);\n    return result as unknown as {acct_name};\n  }} catch {{\n    return null;\n  }}\n}}\n\n"
        ));

        // fetchAll — batch
        f.push_str(&format!(
            "/** Fetches multiple `{acct_name}` accounts. Missing accounts are `null`. */\nexport async function fetchAll{acct_name}(\n  program: naclac.LegacyProgram,\n  addresses: Array<naclac.PublicKey | string>,\n  opts?: {{ dropCorrupted?: boolean }},\n): Promise<Array<{acct_name} | null>> {{\n  const results = await program.account['{acct_name}'].fetchMultiple(addresses, opts);\n  return results as unknown as Array<{acct_name} | null>;\n}}\n\n"
        ));

        // fetchAllOwned — all accounts owned by program
        f.push_str(&format!(
            "/** Fetches all on-chain `{acct_name}` accounts owned by this program. */\nexport async function fetchAll{acct_name}ByOwner(\n  program: naclac.LegacyProgram,\n  options?: {{ dropCorrupted?: boolean; filters?: any[] }},\n): Promise<Array<{{ publicKey: naclac.PublicKey; account: {acct_name} }}>> {{\n  const results = await program.account['{acct_name}'].all(options);\n  return results as unknown as Array<{{ publicKey: naclac.PublicKey; account: {acct_name} }}>;\n}}\n"
        ));

        fs::write(
            clients_dir.join(format!("accounts/legacy/{file_name}.ts")),
            f,
        )?;
    }
    if !idl.accounts.is_empty() {
        fs::write(clients_dir.join("accounts/legacy/index.ts"), accounts_index)?;
    }

    Ok(())
}
